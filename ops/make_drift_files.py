"""Writes the two golden shaped files used by Lesson 8.4. Run once; the output is committed.
1. eval/golden/drift/versioned_policy_questions.yaml: a VERBATIM copy of the 13 golden questions whose evidence is a versioned policy edition. No new questions, no edits.
2. eval/golden/drift/drift_before.yaml and drift_after.yaml: 3 DRAFT questions (written by Claude, for the author to review) whose answer changed when edition 2026.3 was published.
   Same question in both files; only the evidence differs. They are not in golden.yaml, so golden.yaml is untouched (CLAUDE.md principle 5).
"""
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
golden = yaml.safe_load((ROOT / "eval/golden/golden.yaml").read_text(encoding="utf-8"))
pat = re.compile(r"brightcart/v3/policy/[^/]+/[^/]+/[^/]+$")
subset = [g for g in golden if any(pat.match(e["doc_id"]) for e in g.get("evidence") or [])]
out = ROOT / "eval/golden/drift"
out.mkdir(parents=True, exist_ok=True)
(out / "versioned_policy_questions.yaml").write_text("# Verbatim copy of the golden questions whose evidence is a versioned policy edition. Generated by ops/make_drift_files.py. Do not edit.\n"
                                                    + yaml.safe_dump(subset, sort_keys=False, allow_unicode=True, width=140), encoding="utf-8")
P = "brightcart/v3/policy/"
DRAFTS = [
    ("d01", "how many days does a us customer have to return electronics", f"{P}returns/electronics-return-window/2026.1", "The rule for this edition is: **21 calendar days**.",
     f"{P}returns/electronics-return-window/2026.3", "The rule for this edition is: **30 calendar days**."),
    ("d02", "how much notice does an enterprise customer in the eu have to give to cancel", f"{P}subscriptions/enterprise-cancellation/2026.1", "The rule for this edition is: **45 days notice**.",
     f"{P}subscriptions/enterprise-cancellation/2026.3", "The rule for this edition is: **30 days notice for EU enterprise contracts signed after 2026-09-01**."),
    ("d03", "how long do we keep an eu consumer's support chat transcripts", f"{P}privacy/support-transcript-retention/2026.1", "The rule for this edition is: **365 days**.",
     f"{P}privacy/support-transcript-retention/2026.3", "The rule for this edition is: **180 days for EU consumer support transcripts**."),
]
for world, idx in (("before", 2), ("after", 4)):
    items = [{"id": d[0], "question": d[1], "evidence": [{"doc_id": d[idx], "text": d[idx + 1]}], "answerable": True, "tags": ["drift", "edition", "draft"],
              "note": f"DRAFT by Claude, not reviewed. Evidence for the {world} world."} for d in DRAFTS]
    (out / f"drift_{world}.yaml").write_text(f"# DRAFT drift questions, evidence as of the {world} world (edition 2026.3 {'not yet published' if world == 'before' else 'published'}). Written by Claude, to be reviewed by the author.\n"
                                            + yaml.safe_dump(items, sort_keys=False, allow_unicode=True, width=140), encoding="utf-8")
print(len(subset), "versioned policy questions copied;", len(DRAFTS), "draft drift questions")
